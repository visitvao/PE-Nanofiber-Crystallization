
C --------------------------------------------------------------------
       SUBROUTINE SUBLOCALCHEMISTRY(CHAINLENGTH, NOS, LC, LCR, IFRING)
C --------------------------------------------------------------------
C
C  SUBROUTINE TO DETERMINE THE LOCAL CHEMISTRY OF THE CHAIN   
C  IN THE 2NND_RIS MODEL
C
C  LOCAL CHEMISTRY OF PE IS ONLY OF ONE TYPE: (A->A) TYPE VECTORS ON
C  REAL AND 2NND CHAIN. THUS, LC = 1.
C  LOCAL CHEMISTY OF POE HAS THREE TYPES. THE REAL CHAIN ALWAYS STARTS
C  (A-A-B-) SEQUENCE. THE 2NND CHAIN STARTS WITH (A-B-A-) SEQUENCE.
C  THEREFORE, THE FIRST VECTOR CONNECTING BEADS i AND i+2 ON 2NND IS
C  (A->A) WITH LC = 4, THE SECOND IS (B->A) WITH LC = 2, AND THE THIRD
C  IS (A->B) WITH LC = 3.
      INTEGER   I
      INTEGER   CHAINL
      PARAMETER (CHAINL=100)

      INTEGER   NOS
      INTEGER  LC(-2:CHAINL+3)
      INTEGER  LCR(-2:CHAINL+3)
      INTEGER   CHAINLENGTH
      INTEGER  IFRING

      IF( NOS.EQ.1 ) THEN
	DO I = 1, CHAINLENGTH
	  LC(I) = 1
	  LCR(I) = 1
	ENDDO
      ENDIF

      IF( NOS.EQ.3 ) THEN
	DO I = 1, CHAINLENGTH, 3
	  LC(I) = 4
	  LCR(I) = 4
	  IF((I+1).LE.CHAINLENGTH) THEN
		LC(I+1) = 2
		LCR(I+1) = 3
	  ENDIF
	  IF((I+2).LE.CHAINLENGTH) THEN 
		LC(I+2) = 3
		LCR(I+2) = 2
	  ENDIF
	ENDDO
      ENDIF

      IF(IFRING.EQ.1) THEN
	LC(0) = LC(CHAINLENGTH)
	LC(-1) = LC(CHAINLENGTH-1)
	LC(-2) = LC(CHAINLENGTH-2)
	LC(CHAINLENGTH+1) = LC(1)	
	LC(CHAINLENGTH+2) = LC(2)	
	LC(CHAINLENGTH+3) = LC(3)
	LCR(0) = LCR(CHAINLENGTH)
	LCR(-1) = LCR(CHAINLENGTH-1)
	LCR(-2) = LCR(CHAINLENGTH-2)
	LCR(CHAINLENGTH+1) = LCR(1)	
	LCR(CHAINLENGTH+2) = LCR(2)	
	LCR(CHAINLENGTH+3) = LCR(3)
      ENDIF
	
      RETURN
      END




