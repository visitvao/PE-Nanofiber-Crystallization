
      SUBROUTINE SUBBUILDINITIALCHAINNRRW(BONDVECTOR,ISEED,LC,
     >			SNNDPROB,CONDPROB)

      INTEGER  CHAINL, LATTICES, CHAINN

      PARAMETER (CHAINL=100,LATTICES=100,CHAINN=200)

      INTEGER  I, II, J, K
      INTEGER  ISEED
      INTEGER  XTEST, YTEST, ZTEST
      INTEGER  CHAINLENGTH, CHAINNUMBER
      INTEGER  LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      INTEGER  ISUCCESSFULINDEX
      INTEGER  THISVECTORTYPE, OLDVECTORTYPE
      INTEGER  SUCCESSFULINDEX(12)
      INTEGER  X(CHAINN,-2:CHAINL+3), Y(CHAINN,-2:CHAINL+3),
     >         Z(CHAINN,-2:CHAINL+3)
      INTEGER  XP(CHAINN,-2:CHAINL+3), YP(CHAINN,-2:CHAINL+3),
     >         ZP(CHAINN,-2:CHAINL+3)
      INTEGER  BONDVECTOR(12,3)
      INTEGER  LC(-2:CHAINL+3)

      REAL     RAN1, DUMMY, PROB
      REAL     SNNDPROB(4,4)
      REAL     CONDPROB(4,4,4)

      COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP


      DO II = 1, CHAINNUMBER

   10 DUMMY = RAN1(ISEED)*FLOAT(LATTICESIZEX)
      X(II,1) = INT(DUMMY)
      DUMMY = RAN1(ISEED)*FLOAT(LATTICESIZEY)
      Y(II,1) = INT(DUMMY)
      DUMMY = RAN1(ISEED)*FLOAT(LATTICESIZEZ)
      Z(II,1) = INT(DUMMY)

      XP(II,1) = X(II,1)
      YP(II,1) = Y(II,1)
      ZP(II,1) = Z(II,1)


      DUMMY = RAN1(ISEED)*12.0
      K = INT(DUMMY) + 1
      XP(II,2) = XP(II,1) + BONDVECTOR(K,1)
      YP(II,2) = YP(II,1) + BONDVECTOR(K,2)
      ZP(II,2) = ZP(II,1) + BONDVECTOR(K,3)

      X(II,2) = XP(II,2)
      Y(II,2) = YP(II,2)
      Z(II,2) = ZP(II,2)
      CALL SUBFOLDEDPOINT(X(II,2),Y(II,2),Z(II,2))


      DO I = 3, CHAINLENGTH

        ISUCCESSFULINDEX = 0
        DO J = 1, 12
          SUCCESSFULINDEX(J) = 0
        ENDDO

        DO J = 1, 12
          XTEST = XP(II,I-1) + BONDVECTOR(J,1)
          YTEST = YP(II,I-1) + BONDVECTOR(J,2)
          ZTEST = ZP(II,I-1) + BONDVECTOR(J,3)

          IF( ( XP(II,I-2) .EQ. XTEST ) .AND.
     >        ( YP(II,I-2) .EQ. YTEST ) .AND.
     >        ( ZP(II,I-2) .EQ. ZTEST ) ) GO TO 100

	    CALL SUBSNNDRISSTATE(XTEST,YTEST,ZTEST,
     >  	  		 XP(II,I-2),YP(II,I-2),ZP(II,I-2),
     >				 THISVECTORTYPE)
	    IF(I.EQ.3) THEN
	        PROB = SNNDPROB(THISVECTORTYPE,LC(1))
		IF(PROB.LT.1E-10) GO TO 100
	    ELSE
		PROB = CONDPROB(OLDVECTORTYPE,THISVECTORTYPE,LC(I-2))
		IF(PROB.LT.1E-10)GO TO 100
	    ENDIF

          ISUCCESSFULINDEX = ISUCCESSFULINDEX + 1
          SUCCESSFULINDEX(ISUCCESSFULINDEX) = J

  100   ENDDO
        IF(ISUCCESSFULINDEX.EQ.0) THEN
          WRITE(9,*) 'LOCKED SITUATION ON BEAD; CHAIN'
          WRITE(9,*) I, II
          WRITE(9,*) ' '
	  GOTO 10
        ENDIF

        DUMMY = RAN1(ISEED)*FLOAT(ISUCCESSFULINDEX)
        K = INT(DUMMY) + 1
        XP(II,I) = XP(II,I-1) + BONDVECTOR(SUCCESSFULINDEX(K),1)
        YP(II,I) = YP(II,I-1) + BONDVECTOR(SUCCESSFULINDEX(K),2)
        ZP(II,I) = ZP(II,I-1) + BONDVECTOR(SUCCESSFULINDEX(K),3)
        X(II,I) = XP(II,I)
        Y(II,I) = YP(II,I)
        Z(II,I) = ZP(II,I)
        CALL SUBFOLDEDPOINT(X(II,I),Y(II,I),Z(II,I))

	CALL SUBSNNDRISSTATE(XP(II,I),YP(II,I),ZP(II,I),
     >  		     XP(II,I-2),YP(II,I-2),ZP(II,I-2),
     >			     OLDVECTORTYPE)

      ENDDO

      ENDDO

      RETURN
      END
