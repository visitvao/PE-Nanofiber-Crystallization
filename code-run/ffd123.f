          ENDIF
        ELSE
C  ------------------------------------------------------------ qsumsquare = 1 / 3
C  THE KIND OF CONFIGURATION WHERE THE SELECTED BEAD HAS A
C  CHOICE OF THREE ALTERNATIVES
          IF( ( QSUMSQUARE .NE. 1 ) .AND. ( QSUMSQUARE .NE. 3 ) ) THEN
              WRITE(99,*) 'PROBLEM WITH TYPE OF MOVE'
              WRITE(99,*) ' QSUMSQUARE NOT FOUND '
              GO TO 999
          ENDIF
C  ----------------------
          CALL SUBALTERNATIVPOSTHREE(
     >      XP(IPRESENTCHAIN,IPRESENTBEAD-1),
     >      YP(IPRESENTCHAIN,IPRESENTBEAD-1),
     >      ZP(IPRESENTCHAIN,IPRESENTBEAD-1),
     >      XP(IPRESENTCHAIN,IPRESENTBEAD),
     >      YP(IPRESENTCHAIN,IPRESENTBEAD),
     >      ZP(IPRESENTCHAIN,IPRESENTBEAD),
     >      XP(IPRESENTCHAIN,IPRESENTBEAD+1),
     >      YP(IPRESENTCHAIN,IPRESENTBEAD+1),
     >      ZP(IPRESENTCHAIN,IPRESENTBEAD+1),
     >      XALTERNATIVE,YALTERNATIVE,ZALTERNATIVE,
     >      BONDVECTOR, IHISTOMOVE, ISEED, QSUMSQUARE)
