     >    YP(IPRESENTCHAIN,1),
     >    ZP(IPRESENTCHAIN,1),
     >    XP(IPRESENTCHAIN,2),
     >    YP(IPRESENTCHAIN,2),
     >    ZP(IPRESENTCHAIN,2),
     >    XALTERNATIVE,YALTERNATIVE,ZALTERNATIVE,
