      IF( IFEXCLUDEDVOLUME .EQ. 1 ) THEN
C  -------------------------------
        CALL SUBTOTALENERGY(BONDVECTOR, BONDVECTORSECONDSHELL,
     >    RT, IFRING, ENERGYINTERFIRSTSHELL, ENERGYINTERSECONDSHELL,
