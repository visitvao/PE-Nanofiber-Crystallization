      write(10,27) energyinterthirdshell,
     >                               ' ; energyinterthirdshell(F8.3)'
      WRITE(10,*) ' '

      WRITE(10,9) IBIGLOOP + INITIALMOVE
      DO II = 1, CHAINNUMBER
        WRITE(10,10) II, XP(II,1), YP(II,1), ZP(II,1)
        DO 34 I = 2, CHAINLENGTH
          DO J = 1, 12
