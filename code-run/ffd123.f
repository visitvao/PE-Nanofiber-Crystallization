      DO 1001 IBIGLOOP = 1, CHAINMOVES
      DO 1002 IMEDLOOP = 1, CHAINNUMBER
      DO 1003 ISMALLOOP = 1, CHAINLENGTH

      MICROMOVES = MICROMOVES + 1

C  xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx

C  SELECT CURRENT CHAIN/BEAD FOR MOVENEMT
      IF(ISEQUENCE.EQ.0) THEN
