C         ...................
C         NO COMMON BLOCKS
C  ----------------------
        IHISTOMOVE = 19
      ELSE IF( ( IPRESENTBEAD .EQ. CHAINLENGTH ) .AND.
     >         ( IFRING .NE. 1 ) ) THEN
C  ----------------------
        CALL SUBALTERNATIVPOSEND(
     >    XP(IPRESENTCHAIN,CHAINLENGTH),
     >    YP(IPRESENTCHAIN,CHAINLENGTH),
     >    ZP(IPRESENTCHAIN,CHAINLENGTH),
     >    XP(IPRESENTCHAIN,CHAINLENGTH-1),
     >    YP(IPRESENTCHAIN,CHAINLENGTH-1),
     >    ZP(IPRESENTCHAIN,CHAINLENGTH-1),
