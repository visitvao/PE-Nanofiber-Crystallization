
C --------------------------------------------------------------------
      PROGRAM SNND
C --------------------------------------------------------------------
C
C  PROGRAM TO SIMULATE ONE OR MORE CHAINS ON THE NEW 2NND-
C  (SECOND NEAREST NEIGHBOR DIAMOND) LATTICE.
C
C  EXCLUDED VOLUME OF THE INTERMEDIATE (DIAMOND LATTICE) BEADS 
C  IS INCLUDED STATISTICALLY (not definite for a certain conformation)
C
C  THE 2NND LATTICE IS A DISTORTED SIMPLE CUBIC LATTICE BUT WITH
C  COORDINATION NUMBER 12 INSTEAD OF 6.
C  TO SEE THIS LATTICE AS A SIMPLE CUBIC LATTICE ALLOWS FOR USING
C  THE FAST INTEGER NUMBERS.
C  A TRANSFORMATION ALWAYS ALLOWS THE TRANSITION BETWEEN THESE TWO
C  REPRESENTATIONS.
C
C  OUTLINE OF THE PROGRAM:
C  -----------------------
C  - BUILD THE INITIAL CONFIGURATION OF THE CHAIN (BIASED SAMPLING)
C     - START AT A CERTAIN POINT (ARBITRARY, E.G. (1,1,1))
C     - ADD BOND BY BOND RANDOMLY
C        - CHECK ALL POSSIBLE DIRECTIONS OF THE NEW BOND
C        - SELECT EQUALLY BETWEEN THE POSSIBLE BONDS
C          (SAW-RESTICTION OR NRRW-RESTRICTION OF BEADS!)
C
C  - SELECT A CHAIN (IF MORE THAN ONE PRESENT)
C
C  - MOVE THE CHAIN
C     - SELECT A BEAD (SEQUENTIALLY OR RANDOMLY)
C     - END BEAD:
C        - ASSIGN RANDOM NEW DIRECTION OF THE LAST BOND
C           - IF FREE: MOVE THE BOND
C           - IF OCCUPIED: LEAVE THE BOND AT OLD POSITION BUT COUNT
C                          THIS CONFORMATION AGAIN
C     - BEAD I IN CHAIN:
C        - DETERMINE VECTOR  BEAD(I-1) -> BEAD(I+1)
C        - LOOK UP THE 2-6 POSSIBLE VECTORS FOR BEAD(I) -> BEAD(I')
C        - DETERMINE BEAD(I')
C          (VECTOR BEAD(I-1) -> BEAD(I') MUST BE IN LIST OF POSSIBLE
C           VECTORS;  CHECK ALSO FOR VECTOR BEAD(I+1) -> BEAD(I'))
C        - CHECK EXCLUDED VOLUME RESTRICTIONS FOR BEAD(I') - IF DESIRED
C        - DETERMINE THE INCREASE IN ENERGY FOR THE NEW CONFORMATION
C          OR THE PROBABILITY OF THE MOVE AND APPLY THE METROPOLIS CRITERION
C          - LOCAL INTERACTIONS (RIS-CHAIN)
C          - LONG RANGE INTERACTIONS
C
C          PROBABILITY FOR MOVING BEAD(I) - LOCAL INTERACTIONS
C              APPLY THE ALTERNATIVE RIS-DESCTIPTION FOR THE 2NND-LATTICE.
C          THE CONDITIONAL PROBABILITIES OF TWO SUCCESSIVE 1-3 VECTORS ON THE
C          2NND-LATTICE ARE IMPORTED VIA THE FILE "INPUT_COND_PROB"
C          INDICES:  1: THE BEADS 1-3 ARE 5.00 ANGSTROM APART (tt)
C                    2: THE BEADS 1-3 ARE 4.33 ANGSTROM APART (t+, t-, +t, -t)
C                    3: THE BEADS 1-3 ARE 3.53 ANGSTROM APART (++, --)
C                    4: THE BEADS 1-3 ARE 2.50 ANGSTROM APART (+-, -+)
C
C          PROBABILITY FOR MOVING BEAD(I) - LONG RANGE INTERACTIONS
C              IMPLEMENT THE FORCE FIELD ACCORDING TO THE NOTES OF DR. MATTICE.
C
C  - MONITOR THE QUANTITIES:
C     - ATTEMPTS TO MOVE THE DIFFERENT BEADS
C     - ATTEMPTS FOR THE DIFFERENT MOVES
C
C
C   `````````````````````````````````````````````````````````````````````````
C   IFEXCLUDEDVOLUME: CHANGE THE EXCLUDED VOLUME RESTRICTIONS OF THE CHAIN(S)
C
C   => DEFAULT: IFEXCLUDEDVOLUME = 1  ---> SAW
C               IFEXCLUDEDVOLUME = 0  ---> NRRW (I.E. A RIS CHAIN)
C
C   IFRING:  ALLOW FOR RING-CONFORMATIONS
C               IFRING = 1  --->  THIS IS A RING CONFORMATION
C   ( INITIAL CONDFORMATIONS ARE SELF-AVOIDING !! )
C   `````````````````````````````````````````````````````````````````````````
C
C   VARIABLES:
C   ----------
C   X(CHAINN,-2:CHAINL+3)          : FOLDED COORDINATES; INTEGER; SNND-LATTICE
C   XP(CHAINN,-2:CHAINL+3)         : PARENT COORDINATES; INTEGER; SNND-LATTICE

      INTEGER  CHAINL, LATTICES, CHAINN

C  -------------------------------------------------------------------
C  SPECIFICATION OF THE SYSTEM:
C   - CHAINL     ->  CHAINLENGTH
C   - LATTICES   ->  LATTICESIZEX,Y,Z (= SIZE OF BOX)
C   - ISEQUENCE  ->  = 1  BEADS FOR MOVE PICKED SEQUENTIALLY
C                    = 0  BEADS FOR MOVE PICKED RANDOMLY
C   - CHAINMOVES ->  NUMBER OF CHAIN MOVES ( = MONTE CARLO MOVES )
C  -------------------------------------------------------------------
      PARAMETER (CHAINL=100,LATTICES=100,CHAINN=200)
      INTEGER   NU
      PARAMETER (NU=9)

      INTEGER  I, II, J, K
      INTEGER  NOS
      INTEGER  LC(-2:CHAINL+3)
      INTEGER  LCR(-2:CHAINL+3)
      INTEGER  TYPE1, TYPE2, TYPE3, TYPE4
      INTEGER  A, B, E, F, ae, bf, TEMP
      INTEGER  IBIGLOOP, IMEDLOOP, ISMALLOOP
      INTEGER  ISEED, INITSEED
      INTEGER  CHAINNUMBER
      INTEGER  STOREINTERVAL
      INTEGER  IFEXCLUDEDVOLUME
      INTEGER  IFRING
      INTEGER  IFORMFILM, ZEXTEND
      INTEGER  IRELAX
      INTEGER  INITIALMOVE
      INTEGER  IHISTOMOVE, QSUM, QSUMSQUARE
      INTEGER  CHAINLENGTH, ISEQUENCE
      INTEGER  LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      INTEGER  IPRESENTCHAIN, IPRESENTBEAD,ILATTICESIZEX_NEW
      INTEGER  MICROMOVES, CHAINMOVES
      INTEGER  IFIRSTVECTOR,  IXFIRSTVECTOR
      INTEGER  ISECONDVECTOR, IXSECONDVECTOR
      INTEGER  ITHIRDVECTOR,  IXTHIRDVECTOR
      INTEGER  IFOURTHVECTOR, IXFOURTHVECTOR
      INTEGER  IFIFTHVECTOR
      INTEGER  XALTERNATIVE, YALTERNATIVE, ZALTERNATIVE
      INTEGER  XALTERNATIVEFOLDED, YALTERNATIVEFOLDED,
     >         ZALTERNATIVEFOLDED
      INTEGER  X(CHAINN,-2:CHAINL+3), Y(CHAINN,-2:CHAINL+3),
     >         Z(CHAINN,-2:CHAINL+3)
      INTEGER  XTEST(CHAINN,-2:CHAINL+3), YTEST(CHAINN,-2:CHAINL+3),
     >         ZTEST(CHAINN,-2:CHAINL+3)
      INTEGER  XP(CHAINN,-2:CHAINL+3), YP(CHAINN,-2:CHAINL+3),
     >         ZP(CHAINN,-2:CHAINL+3)
      INTEGER  HISTOPRESENTBEADTOTAL(CHAINL)
      INTEGER  HISTOPRESENTBEAD(CHAINN,CHAINL)
      INTEGER  HISTOPRESENTCHAIN(CHAINN)
      INTEGER  HISTOMOVETOTAL(22), HISTOMOVEMADETOTAL(22)
      INTEGER  HISTOMOVE(CHAINN,22), HISTOMOVEMADE(CHAINN,22)
      INTEGER  BONDVECTOR(12,3)
      INTEGER  BONDVECTORSECONDSHELL(42,3)
      integer  bondvectorthirdshell(92,3)
      INTEGER  BONDDIRECTION(CHAINN,CHAINL)
      INTEGER  BEADOCCUPANCY(0:LATTICES-1,0:LATTICES-1,0:LATTICES-1)
      INTEGER  BEADOCCUPANCYTEST(0:LATTICES-1,0:LATTICES-1,
     >                           0:LATTICES-1)

      REAL     RAN1, DUMMY, RT
      REAL     LOCALPROB, LOCALENERGY
      REAL     TOTALENERGYSTART, TOTALENERGY
      REAL     LONGRANGEENERGY, MOVEPROB
      REAL     DELTAENERGY
      REAL     ENERGYINTERFIRSTSHELL, ENERGYINTERSECONDSHELL
      real     energyinterthirdshell
      REAL     SNNDPROB(4,4)
      REAL     CONDPROB(4,4,4)
      REAL     ENERGYVALUE(CHAINN)
      REAL     UBAR(NU,NU,4)
      REAL     ACCEPTRATE
      REAL     SS

      CHARACTER  GARB1*50
      CHARACTER  POLYMER*18, LITERATURE*47
      CHARACTER  CHTAB

      COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      COMMON  /BEADOCCUPANCY/   BEADOCCUPANCY
      COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP

C  xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx

      CHTAB = CHAR(9)

C  INITIALIZE
      OPEN(UNIT=9,ERR=155,STATUS='OLD',FILE='CONFORMATION.START')
      WRITE(6,*) 'INPUT FILE = _CONFORMATION.START_'
      A = 1
      GO TO 156
  155 OPEN(UNIT=9,FILE='INPUT.DAT')
      WRITE(6,*) 'INPUT FILE = _INPUT.DAT_'
      A = 2
  156 READ(9,6)  POLYMER
      READ(9,7)  LITERATURE
      READ(9,8)  GARB1
      READ(9,9)  CHAINLENGTH
      READ(9,9)  LATTICESIZEX
      READ(9,9)  LATTICESIZEY
      READ(9,9)  LATTICESIZEZ
      READ(9,9)  CHAINNUMBER
      READ(9,9)  CHAINMOVES
      READ(9,9)  STOREINTERVAL
      READ(9,9)  ISEQUENCE
      READ(9,9)  ISEED
      READ(9,9)  TEMP
      READ(9,9)  IFEXCLUDEDVOLUME
      READ(9,9)  IFRING
      READ(9,9)  NOS
      READ(9,9)  IFORMFILM
      READ(9,14) ENERGYINTERFIRSTSHELL
      READ(9,14) ENERGYINTERSECONDSHELL
      read(9,14) energyinterthirdshell
C      read(9,9)  ILATTICESIZEX_NEW
      print*,'OK!'

      INITSEED = ISEED

      IF( CHAINLENGTH .GT. CHAINL ) THEN
        WRITE(15,*) 'ERROR IN INPUT FILE'
        WRITE(15,*) 'SPECIFIED CHAINLENGTH EXCEEDING'
        WRITE(15,*) 'PROGRAMMED MAXIMUM LENGTH'
        GO TO 999
      ENDIF
      IF( LATTICESIZEX .GT. LATTICES .OR. LATTICESIZEY .GT. LATTICES
     > 	 .OR. LATTICESIZEZ .GT. LATTICES ) THEN
        WRITE(15,*) 'ERROR IN INPUT FILE'
        WRITE(15,*) 'SPECIFIED LATTICESIZE EXCEEDING'
        WRITE(15,*) 'PROGRAMMED MAXIMUM SIZE'
        GO TO 999
      ENDIF
      IF( CHAINNUMBER .GT. CHAINN ) THEN
        WRITE(15,*) 'ERROR IN INPUT FILE'
        WRITE(15,*) 'SPECIFIED CHAINNUMBER EXCEEDING'
        WRITE(15,*) 'PROGRAMMED MAXIMUM NUMBER'
        GO TO 999
      ENDIF
      IF( MOD(CHAINMOVES,STOREINTERVAL) .NE. 0) THEN
        WRITE(15,*) 'ERROR IN INPUT FILE'
        WRITE(15,*) 'CHAINMOVES NOT MULTIPLE OF STOREINTERVAL'
        GO TO 999
      ENDIF

      IRELAX = 0
      SS = 0.00001
      IF (IFEXCLUDEDVOLUME.EQ.1.AND.
     >		ABS(ENERGYINTERFIRSTSHELL).LT.SS.AND.
     >		ABS(ENERGYINTERSECONDSHELL).LT.SS.AND.
     >		ABS(energyinterthirdshell).LT.SS) THEN
	WRITE(6,*)'RELAXATION OF BULK'
	IRELAX = 1
      ENDIF

      IF (IFORMFILM.EQ.0) WRITE(6,*)'DYNAMIC RUN'
      IF (IFORMFILM.EQ.1) WRITE(6,*)'NEW FILM FORMATION'
      IF (IFORMFILM.EQ.2) WRITE(6,*)'NEW FIBER FORMATION'
      IF (IFORMFILM.EQ.3) WRITE(6,*)'NEW DROPLET FORMATION'

C  RT IN  (kJ / mol)
      RT = 8.3145 / 1000.0 * FLOAT(TEMP)

C  DETERMINE THE LOCAL CHEMISTRY:
C  ----------------------
      CALL SUBLOCALCHEMISTRY(CHAINLENGTH, NOS, LC, LCR, IFRING)
C     ...................
C  DETERMINE THE LOCAL CHEMISTRY:

C  CALCULATE THE STATISTICAL WEIGHTS:
C  ----------------------
      CALL SUBSTATWEIGHTS(TEMP, RT, UBAR)
C     ...................
C  CALCULATE THE STATISTICAL WEIGHTS:

C  CALCULATE THE CONDITIONAL PROBABILITIES:
C  ----------------------
      CALL SUBCONDPROB(UBAR,CONDPROB,SNNDPROB,NOS)
C     ...................
C  CALCULATE THE CONDITIONAL PROBABILITIES:

      MICROMOVES    = 0
      IPRESENTBEAD  = 0
      IBIGLOOP      = 0
      IHISTOMOVE    = 0
      INITIALMOVE   = 0

      DO II = 1, CHAINN
        ENERGYVALUE(II) = 0.0
      ENDDO

      DO I = 1, 22
        HISTOMOVETOTAL(I) = 0
        HISTOMOVEMADETOTAL(I) = 0
        DO II = 1, CHAINN
          HISTOMOVE(II,I) = 0
          HISTOMOVEMADE(II,I) = 0
        ENDDO
      ENDDO
      DO I = 1, CHAINLENGTH
        HISTOPRESENTBEADTOTAL(I) = 0
        DO II = 1, CHAINN
          HISTOPRESENTBEAD(II,I) = 0
        ENDDO
      ENDDO
      DO I = -2, CHAINLENGTH+3
        DO II = 1, CHAINN
          X(II,I) = 0
          Y(II,I) = 0
          Z(II,I) = 0
          XP(II,I) = 0
          YP(II,I) = 0
          ZP(II,I) = 0
        ENDDO
      ENDDO
      DO I = 1, 3
        DO J = 1, 12
          BONDVECTOR(J,I) = 0
        ENDDO
      ENDDO
      DO I = 0, LATTICESIZEZ-1
        DO J = 0, LATTICESIZEY-1
          DO K = 0, LATTICESIZEX-1
            BEADOCCUPANCY(K,J,I) = 0
            BEADOCCUPANCYTEST(K,J,I) = 0
          ENDDO
        ENDDO
      ENDDO

    6 FORMAT(A18)
    7 FORMAT(A47)
    8 FORMAT(A50)
    9 FORMAT(I8)
   10 FORMAT(4I7)
  101 FORMAT(4I4)
  102 FORMAT(I12)
   13 FORMAT(10I2)
   14 FORMAT(F8.3)
   15 FORMAT(I8,12F12.3)
   25 FORMAT(I8,10X,A28)
   26 FORMAT(A18,A29)
   27 FORMAT(F8.3,10X,A30)
   31 FORMAT(9I3,F7.1)

      OPEN(UNIT=11,FILE='ENERGY')
      IF( IFEXCLUDEDVOLUME .EQ. 1 ) THEN
        IF( CHAINNUMBER .EQ. 1 ) THEN
          WRITE(11,*)
     >     'MCS, DELTAENERGY, TOTALENERGY, ENERGY PER CHAIN'
        ELSE IF( CHAINNUMBER .LE. 10 ) THEN
          WRITE(11,*)
     >     'MCS, DELTAENERGIES, TOTALENERGY, ENERGY PER CHAIN'
        ELSE
          WRITE(11,*) 'MCS, TOTALENERGY, ENERGY PER CHAIN'
        ENDIF
      ELSE
        IF( CHAINNUMBER .LE. 10 ) THEN
          WRITE(11,*) 'MCS, DELTAENERGIES'
        ENDIF
      ENDIF

      OPEN(UNIT=14,FILE='ENERGY_INTRA_INTER')
      WRITE(14,*) 'TOTAL ENERGY: INTRAMOLECULAR, INTERMOLECULAR'
      OPEN(UNIT=18,FILE='OVERALL_DISTR_FUNC')
      WRITE(18,*) 'MCS    %(1ST SHELL)    %(2ND SHELL)    %(3rd shell)'

	
c      DUMMY = RAN1(-3)
	print*,'OK2'
C  INITIALIZE

C  xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx

C  GET THE LIST OF ALL POSSIBLE BOND VECTORS
C  ----------------------
      CALL SUBGETBONDVECTORS(BONDVECTOR)
C     ...................
C     NO COMMON BLOCKS
C  ----------------------
C  GET THE LIST OF ALL POSSIBLE BOND VECTORS
C  GET THE LIST OF ALL POSSIBLE BOND VECTORS OF THE SECOND SHELL
C  ----------------------
      CALL SUBGETBONDVECTORSECONDSHELL(BONDVECTOR,
     >                                 BONDVECTORSECONDSHELL)
C     ...................
C     NO COMMON BLOCKS
C  ----------------------
C  GET THE LIST OF ALL POSSIBLE BOND VECTORS OF THE SECOND SHELL
C  GET THE LIST OF ALL POSSIBLE BOND VECTORS OF THE third SHELL
C  ----------------------
      CALL subgetbondvectorthirdshell(BONDVECTOR,
     >           BONDVECTORSECONDSHELL, bondvectorthirdshell)
C     ...................
C     NO COMMON BLOCKS
C  ----------------------
C  GET THE LIST OF ALL POSSIBLE BOND VECTORS OF THE third SHELL

C  xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx
	
C  BUILD/READ THE INITIAL CHAIN(S)
      IF( A .EQ. 2 ) THEN
        IF( IFRING .EQ. 1 ) THEN
C  ----------------------
         CALL SUBBUILDINITIALCHAINRING(BONDVECTOR,ISEED)
C        ...................
C        COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
C     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
C        COMMON  /BEADOCCUPANCY/   BEADOCCUPANCY
C        COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP
C  ----------------------
        ELSE IF( IFEXCLUDEDVOLUME .EQ. 1 ) THEN
C  ----------------------
         CALL SUBBUILDINITIALCHAINSAW(BONDVECTOR,ISEED,LC,
     >			SNNDPROB,CONDPROB)
C        ...................
C        COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
C     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
C        COMMON  /BEADOCCUPANCY/   BEADOCCUPANCY
C        COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP
C  ----------------------
        ELSE
C  ----------------------
         CALL SUBBUILDINITIALCHAINNRRW(BONDVECTOR,ISEED,LC,
     >			SNNDPROB,CONDPROB)
C        ...................
C        COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
C     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
C        COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP
C  ----------------------
        ENDIF
      ELSE
       READ(9,8) GARB1
       READ(9,9) INITIALMOVE
       DO II = 1, CHAINNUMBER
         READ(9,10) B, XP(II,1), YP(II,1), ZP(II,1)
         READ(9,13) (BONDDIRECTION(II,I), I=2,CHAINLENGTH)
       ENDDO
       DO II = 1, CHAINNUMBER
         DO I = 2, CHAINLENGTH
           XP(II,I) = XP(II,I-1) + BONDVECTOR(BONDDIRECTION(II,I),1)
           YP(II,I) = YP(II,I-1) + BONDVECTOR(BONDDIRECTION(II,I),2)
           ZP(II,I) = ZP(II,I-1) + BONDVECTOR(BONDDIRECTION(II,I),3)
         ENDDO
       ENDDO
C  -------------------------------
       CALL SUBFOLDEDCHAIN(XP,YP,ZP,X,Y,Z)
C      ...................
C        COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
C     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
C  -------------------------------
       DO II = 1, CHAINNUMBER
         DO I = 1, CHAINLENGTH
           BEADOCCUPANCY(X(II,I),Y(II,I),Z(II,I)) = 1
         ENDDO
       ENDDO
      ENDIF
      CLOSE(9)
C  BUILD/READ THE INITIAL CHAIN(S)

C  APPEND THE FIRST AND LAST BEADS FOR RING-TREATMENT
      IF (IFRING.EQ.1) THEN
      DO II = 1, CHAINNUMBER
        XP(II,-2) = XP(II,CHAINLENGTH-2)
        YP(II,-2) = YP(II,CHAINLENGTH-2)
        ZP(II,-2) = ZP(II,CHAINLENGTH-2)
        XP(II,-1) = XP(II,CHAINLENGTH-1)
        YP(II,-1) = YP(II,CHAINLENGTH-1)
        ZP(II,-1) = ZP(II,CHAINLENGTH-1)
        XP(II,0)  = XP(II,CHAINLENGTH)
        YP(II,0)  = YP(II,CHAINLENGTH)
        ZP(II,0)  = ZP(II,CHAINLENGTH)
        XP(II,CHAINLENGTH+1) = XP(II,1)
        YP(II,CHAINLENGTH+1) = YP(II,1)
        ZP(II,CHAINLENGTH+1) = ZP(II,1)
        XP(II,CHAINLENGTH+2) = XP(II,2)
        YP(II,CHAINLENGTH+2) = YP(II,2)
        ZP(II,CHAINLENGTH+2) = ZP(II,2)
        XP(II,CHAINLENGTH+3) = XP(II,3)
        YP(II,CHAINLENGTH+3) = YP(II,3)
        ZP(II,CHAINLENGTH+3) = ZP(II,3)
        X(II,-2) = X(II,CHAINLENGTH-2)
        Y(II,-2) = Y(II,CHAINLENGTH-2)
        Z(II,-2) = Z(II,CHAINLENGTH-2)
        X(II,-1) = X(II,CHAINLENGTH-1)
        Y(II,-1) = Y(II,CHAINLENGTH-1)
        Z(II,-1) = Z(II,CHAINLENGTH-1)
        X(II,0)  = X(II,CHAINLENGTH)
        Y(II,0)  = Y(II,CHAINLENGTH)
        Z(II,0)  = Z(II,CHAINLENGTH)
        X(II,CHAINLENGTH+1) = X(II,1)
        Y(II,CHAINLENGTH+1) = Y(II,1)
        Z(II,CHAINLENGTH+1) = Z(II,1)
        X(II,CHAINLENGTH+2) = X(II,2)
        Y(II,CHAINLENGTH+2) = Y(II,2)
        Z(II,CHAINLENGTH+2) = Z(II,2)
        X(II,CHAINLENGTH+3) = X(II,3)
        Y(II,CHAINLENGTH+3) = Y(II,3)
        Z(II,CHAINLENGTH+3) = Z(II,3)
      ENDDO
      ENDIF
C  APPEND THE FIRST AND LAST BEADS FOR RING-TREATMENT

C  xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx
C  CHECK FOR CORRECTNESS OF FOLDED COORDINATES
      DO II = 1, CHAINNUMBER
        DO I = 1, CHAINLENGTH
          XTEST(II,I) = X(II,I)
          YTEST(II,I) = Y(II,I)
          ZTEST(II,I) = Z(II,I)
        ENDDO
      ENDDO
C  -------------------------------
      CALL SUBFOLDEDCHAIN(XP,YP,ZP,X,Y,Z)
C     ...................
C        COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
C     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
C  -------------------------------
      DO II = 1, CHAINNUMBER
        DO I = 1, CHAINLENGTH
          IF( (XTEST(II,I) .NE. X(II,I)) .OR.
     >        (YTEST(II,I) .NE. Y(II,I)) .OR.
     >        (ZTEST(II,I) .NE. Z(II,I)) ) THEN
            WRITE(15,*) 'PROBLEM WITH KEEPING TRACK OF'
            WRITE(15,*) 'FOLDED COORDINATES'
            WRITE(15,*) 'AFTER BUILDING INITIAL CHAIN'
            STOP 1
          ENDIF
        ENDDO
      ENDDO
C  CHECK FOR CORRECTNESS OF FOLDED COORDINATES

C  CHECK FOR CORRECTNESS OF BEADOCCUPANCY AND OVERLAPS
      IF( IFEXCLUDEDVOLUME .EQ. 1 ) THEN
      DO I = 0, LATTICESIZEZ-1
        DO J = 0, LATTICESIZEY-1
          DO K = 0, LATTICESIZEX-1
            BEADOCCUPANCYTEST(K,J,I) = 0
          ENDDO
        ENDDO
      ENDDO
      DO II = 1, CHAINNUMBER
        DO I = 1, CHAINLENGTH
          IF(BEADOCCUPANCYTEST(X(II,I),Y(II,I),Z(II,I)).NE.0) THEN
            WRITE(15,*) 'BEADOCCUPANCY GREATER THAN 1'
            WRITE(15,*) 'AFTER BUILDING INITIAL CHAIN'
            STOP 2
          ENDIF
          BEADOCCUPANCYTEST(X(II,I),Y(II,I),Z(II,I)) = 1
        ENDDO
      ENDDO
      DO I = 0, LATTICESIZEZ-1
        DO J = 0, LATTICESIZEY-1
          DO K = 0, LATTICESIZEX-1
            IF(BEADOCCUPANCYTEST(K,J,I).NE.BEADOCCUPANCY(K,J,I)) THEN
              WRITE(15,*) 'PROBLEM WITH BEADOCCUPANCY VS. ~TEST'
              WRITE(15,*) 'AFTER BUILDING INITIAL CHAIN'
              STOP 3
            ENDIF
          ENDDO
        ENDDO
      ENDDO
      ENDIF
C  CHECK FOR CORRECTNESS OF BEADOCCUPANCY AND OVERLAPS

C  xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx

C  FORM A FILM WITH DANGLING ENDS IN Z DIRECTION AND CORRECT THE
C  OCCUPANCIES ON THE NEW EXTENDED LATTICE

      IF (IFORMFILM.EQ.1) THEN 
C  -------------------------------
      CALL SUBFORMFILM(Z,ZP)
C     ...................
C        COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
C     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
C  -------------------------------
	
C  
      ZEXTEND = 3
      LATTICESIZEZ = LATTICESIZEZ * ZEXTEND

      DO I = 0, LATTICESIZEZ-1
        DO J = 0, LATTICESIZEY-1
          DO K = 0, LATTICESIZEX-1
            BEADOCCUPANCY(K,J,I) = 0
            BEADOCCUPANCYTEST(K,J,I) = 0
          ENDDO
        ENDDO
      ENDDO

C  -------------------------------
