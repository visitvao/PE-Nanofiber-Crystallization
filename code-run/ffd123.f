      WRITE(10,25) ISEQUENCE,        ' ; isequence (0=random) (I8)'
      WRITE(10,25) INITSEED,         ' ; initseed             (I8)'
      WRITE(10,25) TEMP,             ' ; temperature (K)      (I8)'
      WRITE(10,25) IFEXCLUDEDVOLUME, ' ; ifexcludedvolume(=1) (I8)'
