        IF( BEADOCCUPANCY(XALTERNATIVEFOLDED,
     >                    YALTERNATIVEFOLDED,
     >                    ZALTERNATIVEFOLDED) .NE. 0 ) THEN
          GO TO 300
        ENDIF
C  - TEST THE SAW-RESTRICTIONS ON THE BEADS:
      ELSE
C  - TEST THE NRRW-RESTRICTIONS ON THE BEADS:
        IF( ( IPRESENTBEAD .GT. 2 ) .OR. ( IFRING .EQ. 1) ) THEN
        IF((XALTERNATIVE.EQ.XP(IPRESENTCHAIN,IPRESENTBEAD-2)) .AND.
     >     (YALTERNATIVE.EQ.YP(IPRESENTCHAIN,IPRESENTBEAD-2)) .AND.
     >     (ZALTERNATIVE.EQ.ZP(IPRESENTCHAIN,IPRESENTBEAD-2))) THEN
          GO TO 300
        ENDIF
        ENDIF
