C       COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP
C  -------------------------------
        TOTALENERGY = TOTALENERGYSTART

C  CALCULATE THE TOTAL ENERGY OF THE SYSTEM

        IF( CHAINNUMBER .LE. 10 ) THEN
          WRITE(11,15) IBIGLOOP+INITIALMOVE, (ENERGYVALUE(II), II=1,
     >       CHAINNUMBER), TOTALENERGY, TOTALENERGY/CHAINNUMBER
          DUMMY = 0.0
          DO II = 1, CHAINNUMBER
            DUMMY = DUMMY + ENERGYVALUE(II)
          ENDDO
          IF( DUMMY - TOTALENERGY-TOTALENERGYSTART .GT. 0.01 ) THEN
            WRITE(78,*) 'PROBLEM WITH TOTALENERGY-RELATVE'
