      WRITE(10,25) NOS,              ' ; nos          (=1, 3) (I8)'
      WRITE(10,25) IFORMFILM,        ' ; iformfilm       (=1) (I8)'
      WRITE(10,27) ENERGYINTERFIRSTSHELL,
     >                               ' ; energyinterfirstshell(F8.3)'
