          ENDIF
        ELSE 
          WRITE(11,15) IBIGLOOP+INITIALMOVE, TOTALENERGY,
     >                 TOTALENERGY/CHAINNUMBER
          DUMMY = 0.0
          DO II = 1, CHAINNUMBER
            DUMMY = DUMMY + ENERGYVALUE(II)
          ENDDO
          IF( DUMMY - TOTALENERGY-TOTALENERGYSTART .GT. 0.01 ) THEN
            WRITE(79,*) 'PROBLEM WITH TOTALENERGY-RELATVE'
c            STOP 79
          ENDIF
        ENDIF
      ELSE
        IF( CHAINNUMBER .LE. 10 ) THEN
          WRITE(11,15) IBIGLOOP+INITIALMOVE, (ENERGYVALUE(II), II=1,
