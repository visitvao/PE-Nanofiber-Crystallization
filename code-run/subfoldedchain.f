
      SUBROUTINE SUBFOLDEDCHAIN(XP,YP,ZP,X,Y,Z)

      INTEGER  CHAINL, LATTICES, CHAINN

      PARAMETER (CHAINL=100,LATTICES=100,CHAINN=200)

      INTEGER  I, II
      INTEGER  CHAINLENGTH
      INTEGER  LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      INTEGER  CHAINNUMBER
      INTEGER  X(CHAINN,-2:CHAINL+3)
      INTEGER  Y(CHAINN,-2:CHAINL+3)
      INTEGER  Z(CHAINN,-2:CHAINL+3)
      INTEGER  XP(CHAINN,-2:CHAINL+3)
      INTEGER  YP(CHAINN,-2:CHAINL+3)
      INTEGER  ZP(CHAINN,-2:CHAINL+3)

      COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ

      DO II = 1, CHAINNUMBER
      DO I = 1, CHAINLENGTH

        X(II,I) = XP(II,I)
        Y(II,I) = YP(II,I)
        Z(II,I) = ZP(II,I)

  103   IF( X(II,I) .GE. LATTICESIZEX ) THEN
          X(II,I) = X(II,I) - LATTICESIZEX
          GO TO 103
        END IF
  104   IF( X(II,I) .LT. 0 ) THEN
          X(II,I) = X(II,I) + LATTICESIZEX
          GO TO 104
        END IF

  105   IF( Y(II,I) .GE. LATTICESIZEY ) THEN
          Y(II,I) = Y(II,I) - LATTICESIZEY
          GO TO 105
        END IF
  106   IF( Y(II,I) .LT. 0 ) THEN
          Y(II,I) = Y(II,I) + LATTICESIZEY
          GO TO 106
        END IF

  107   IF( Z(II,I) .GE. LATTICESIZEZ ) THEN
          Z(II,I) = Z(II,I) - LATTICESIZEZ
          GO TO 107
        END IF
  108   IF( Z(II,I) .LT. 0 ) THEN
          Z(II,I) = Z(II,I) + LATTICESIZEZ
          GO TO 108
        END IF

      ENDDO
      ENDDO

      RETURN
      END
