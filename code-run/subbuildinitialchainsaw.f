
      SUBROUTINE SUBBUILDINITIALCHAINSAW(BONDVECTOR,ISEED,LC,
     >			SNNDPROB,CONDPROB)

      INTEGER  CHAINL, LATTICES, CHAINN

      PARAMETER (CHAINL=100,LATTICES=100,CHAINN=200)

      INTEGER  I, II, J, K
      INTEGER  ILOCK, ISTOP
      INTEGER  ISEED
      INTEGER  XTEST, YTEST, ZTEST
      INTEGER  XI, YI, ZI
      INTEGER  CHAINLENGTH, CHAINNUMBER
      INTEGER  LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      INTEGER  ISUCCESSFULINDEX
      INTEGER  THISVECTORTYPE, OLDVECTORTYPE
      INTEGER  SUCCESSFULINDEX(12)
      INTEGER  X(CHAINN,-2:CHAINL+3), Y(CHAINN,-2:CHAINL+3),
     >         Z(CHAINN,-2:CHAINL+3)
      INTEGER  XP(CHAINN,-2:CHAINL+3), YP(CHAINN,-2:CHAINL+3),
     >         ZP(CHAINN,-2:CHAINL+3)
      INTEGER  BONDVECTOR(12,3)
      INTEGER  BEADOCCUPANCY(0:LATTICES-1,0:LATTICES-1,0:LATTICES-1)
      INTEGER  LC(-2:CHAINL+3)

      REAL     RAN1, DUMMY, PROB
      REAL     SNNDPROB(4,4)
      REAL     CONDPROB(4,4,4)

      COMMON  /SYSTEMSIZE/      CHAINLENGTH, CHAINNUMBER, 
     >			LATTICESIZEX, LATTICESIZEY, LATTICESIZEZ
      COMMON  /BEADOCCUPANCY/   BEADOCCUPANCY
      COMMON  /COORDINATES/     X, Y, Z, XP, YP, ZP

      ILOCK = 0
      DO II = 1, CHAINNUMBER

   10 IF(ILOCK.EQ.1) THEN
      	DO I = 1, ISTOP
          BEADOCCUPANCY(X(II,I),Y(II,I),Z(II,I)) = 0
      	ENDDO
      	ILOCK = 0
      ENDIF
 
      DUMMY = RAN1(ISEED)*FLOAT(LATTICESIZEX)
      X(II,1) = INT(DUMMY)
      DUMMY = RAN1(ISEED)*FLOAT(LATTICESIZEY)
      Y(II,1) = INT(DUMMY)
      DUMMY = RAN1(ISEED)*FLOAT(LATTICESIZEZ)
      Z(II,1) = INT(DUMMY)
      IF( BEADOCCUPANCY(X(II,1),Y(II,1),Z(II,1)) .EQ. 1 ) GO TO 10

      XP(II,1) = X(II,1)
      YP(II,1) = Y(II,1)
      ZP(II,1) = Z(II,1)

      BEADOCCUPANCY(X(II,1),Y(II,1),Z(II,1)) = 1

      DO I = 2, CHAINLENGTH

        ISUCCESSFULINDEX = 0
        DO J = 1, 12
          SUCCESSFULINDEX(J) = 0
        ENDDO

        DO J = 1, 12
          XTEST = XP(II,I-1) + BONDVECTOR(J,1)
          YTEST = YP(II,I-1) + BONDVECTOR(J,2)
          ZTEST = ZP(II,I-1) + BONDVECTOR(J,3)

	  XI = XTEST
	  YI = YTEST
	  ZI = ZTEST

          CALL SUBFOLDEDPOINT(XTEST,YTEST,ZTEST)
          IF( BEADOCCUPANCY(XTEST,YTEST,ZTEST) .EQ. 1 ) GO TO 100

	  IF(I.GT.2) THEN
	    CALL SUBSNNDRISSTATE(XI,YI,ZI,
     >  	  		 XP(II,I-2),YP(II,I-2),ZP(II,I-2),
     >				 THISVECTORTYPE)
	    
	    IF(I.EQ.3) THEN
	        PROB = SNNDPROB(THISVECTORTYPE,LC(1))
		IF(PROB.LT.1E-10) GO TO 100
	    ELSE
		PROB = CONDPROB(OLDVECTORTYPE,THISVECTORTYPE,LC(I-2))
		IF(PROB.LT.1E-10) GO TO 100
	    ENDIF
	  ENDIF

          ISUCCESSFULINDEX = ISUCCESSFULINDEX + 1
          SUCCESSFULINDEX(ISUCCESSFULINDEX) = J

  100   ENDDO

        IF(ISUCCESSFULINDEX.EQ.0) THEN
          WRITE(9,*) 'LOCKED SITUATION ON BEAD; CHAIN'
          WRITE(9,*) I, II
          WRITE(9,*) ' '
	  ILOCK = 1
	  ISTOP = I-1
	  GOTO 10
        ENDIF

        DUMMY = RAN1(ISEED)*FLOAT(ISUCCESSFULINDEX)
        K = INT(DUMMY)
        IF(K.EQ.ISUCCESSFULINDEX) THEN
          WRITE(9,*) 'PROBLEM WITH SELECTING THE BEAD; CHAIN'
          WRITE(9,*) I, II
          STOP 2
        ENDIF
        XP(II,I) = XP(II,I-1) + BONDVECTOR(SUCCESSFULINDEX(K+1),1)
        YP(II,I) = YP(II,I-1) + BONDVECTOR(SUCCESSFULINDEX(K+1),2)
        ZP(II,I) = ZP(II,I-1) + BONDVECTOR(SUCCESSFULINDEX(K+1),3)

        X(II,I) = XP(II,I)
        Y(II,I) = YP(II,I)
        Z(II,I) = ZP(II,I)
        CALL SUBFOLDEDPOINT(X(II,I),Y(II,I),Z(II,I))
        BEADOCCUPANCY(X(II,I),Y(II,I),Z(II,I)) = 1

	IF(I.GT.2) THEN
	CALL SUBSNNDRISSTATE(XP(II,I),YP(II,I),ZP(II,I),
     >  		     XP(II,I-2),YP(II,I-2),ZP(II,I-2),
     >			     OLDVECTORTYPE)
	ENDIF

      ENDDO

      ENDDO

      RETURN
      END
