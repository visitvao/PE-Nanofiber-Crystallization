
C --------------------------------------------------------------------
      SUBROUTINE SUBALTERNATIVPOSEND(X1,Y1,Z1,X2,Y2,Z2,
     >  XALTERNATIVE,YALTERNATIVE,ZALTERNATIVE,BONDVECTOR,ISEED)
C --------------------------------------------------------------------
C
C  SUBROUTINE TO SELECT AN ALTERNATIVE POSITION FOR THE END-BEAD
C  (X1,Y1,Z1). THIS NEW POSITION (XALTERNATIVE,YALTERNATIVE,ZALTERNATIVE)
C  IS SELECTED EVEN AMONG THE VECTORS (BONDVECTOR) POINTING AWAY FROM
C  THE SECOND LAST BOND (X2,Y2,Z2).
C  THE NEW POSITION OF THE LAST BEAD MUST BE DIFFERENT THAN THE INITIAL ONE!!

      INTEGER  ISEED, IDUMMY
      INTEGER  X1,Y1,Z1, X2,Y2,Z2
      INTEGER  XALTERNATIVE,YALTERNATIVE,ZALTERNATIVE
      INTEGER  BONDVECTOR(12,3)

      REAL     RAN1, DUMMY

    5 DUMMY  = RAN1(ISEED)*12.0
      IDUMMY = INT(DUMMY) + 1
      XALTERNATIVE = X2 + BONDVECTOR(IDUMMY,1)
      YALTERNATIVE = Y2 + BONDVECTOR(IDUMMY,2)
      ZALTERNATIVE = Z2 + BONDVECTOR(IDUMMY,3)

      IF( (XALTERNATIVE.EQ.X1) .AND. (YALTERNATIVE.EQ.Y1) .AND.
     >    (ZALTERNATIVE.EQ.Z1) ) THEN
        GO TO 5
      ENDIF

      RETURN
      END
